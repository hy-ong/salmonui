#!/usr/bin/env node
// Static export of the docs site:
// `SITE_EXPORT=1 next build` in docs/site, written to docs/site/out/.
//
// Next.js 16 with `output: 'export'` treats a custom `distDir` as the export
// destination and always keeps its build artifacts in `.next/`. That would
// overwrite the server build `next start` serves, so this script parks an
// existing `.next/` in `.next-export/held/` for the build, then moves the
// export's build artifacts to `.next-export/build/` and restores `.next/`
// (in a `finally`, so a failed build restores it too).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, renameSync, rmSync, statSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WELL_KNOWN_INDEX, writeSiteSkills } from './agent-skills.mjs';
import { stripDocumentOnlyPayloads } from './strip-payloads.mjs';

const site = fileURLToPath(new URL('../../docs/site/', import.meta.url));
const at = (path) => join(site, path);
const serverBuild = at('.next');
const exportDir = at('.next-export');
const held = at('.next-export/held');
const exportBuild = at('.next-export/build');
const nextBin = createRequire(at('package.json')).resolve('next/dist/bin/next');

if (existsSync(held)) {
  // A previous run died between parking and restoring: put it back first.
  if (existsSync(serverBuild)) rmSync(serverBuild, { recursive: true, force: true });
  renameSync(held, serverBuild);
}
rmSync(at('out'), { recursive: true, force: true });
rmSync(exportBuild, { recursive: true, force: true });
mkdirSync(exportDir, { recursive: true });

const parked = existsSync(serverBuild);
if (parked) renameSync(serverBuild, held);
let status = 1;
try {
  const result = spawnSync(process.execPath, [nextBin, 'build'], {
    cwd: site,
    stdio: 'inherit',
    env: { ...process.env, SITE_EXPORT: '1' },
  });
  if (result.error) throw result.error;
  status = result.status ?? 1;
} finally {
  if (existsSync(serverBuild)) renameSync(serverBuild, exportBuild);
  if (parked) renameSync(held, serverBuild);
}

if (status === 0) status = promoteMarkdown(at('out'));
if (status === 0) {
  const stripped = stripDocumentOnlyPayloads(at('out'));
  console.log(`build-export: removed ${stripped.files} RSC payload files of ${stripped.pages} document-only pages`);
}
if (status === 0) status = await exportSkills(at('out'));
if (status === 0 && !existsSync(at('out/index.html'))) {
  console.error('build-export: next build finished but docs/site/out/index.html is missing');
  status = 1;
}
if (status === 0 && existsSync(at('out/api'))) {
  console.error('build-export: docs/site/out/api exists; the export must not contain /api/*');
  status = 1;
}
process.exit(status);

/**
 * Agent Skills: `out/skills/<name>/SKILL.md` and the well-known
 * discovery index `out/.well-known/agent-skills/index.json`, generated by
 * agent-skills.mjs from the same sources as llms.txt on the same SITE_URL.
 * Returns an exit status.
 */
async function exportSkills(out) {
  try {
    const skills = await writeSiteSkills(out);
    console.log(`build-export: ${skills.length} Agent Skills -> out/skills, out/${WELL_KNOWN_INDEX}`);
    return 0;
  } catch (error) {
    console.error(`build-export: Agent Skills failed: ${error.message}`);
    return 1;
  }
}

/**
 * Moves the Markdown versions of the docs pages (AI-readable docs)
 * from `out/markdown/<page>.md`, where the export writes the
 * `app/markdown/[...path]` route handler, to `out/<page>.md` beside each
 * HTML page, then removes `out/markdown/`. Returns an exit status.
 */
export function promoteMarkdown(out) {
  const source = join(out, 'markdown');
  if (!existsSync(source)) {
    console.error('build-export: docs/site/out/markdown is missing; the Markdown pages were not exported');
    return 1;
  }
  const move = (from, to) => {
    for (const name of readdirSync(from)) {
      const src = join(from, name);
      const dest = join(to, name);
      if (statSync(src).isDirectory()) {
        mkdirSync(dest, { recursive: true });
        move(src, dest);
      } else if (name.endsWith('.md')) {
        if (existsSync(dest)) {
          console.error(`build-export: ${dest} already exists; a Markdown page would overwrite it`);
          throw new Error('markdown collision');
        }
        renameSync(src, dest);
      }
    }
  };
  try {
    move(source, out);
  } catch {
    return 1;
  }
  rmSync(source, { recursive: true, force: true });
  return 0;
}
