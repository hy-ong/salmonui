// Generates packages/core/styles/theme.css: the default theme precompiled
// for `:root` and the default `data-salmon-theme` scope. Requires a
// build of @salmonui/core. `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const target = new URL('packages/core/styles/theme.css', root);
const { createThemeCss } = await import(new URL('packages/core/dist/internal/theme/css.js', root).href);
const { FIXED_TOKENS } = await import(new URL('packages/core/dist/internal/theme/fixed.js', root).href);


export function defaultThemeCss() {
  const header =
    '/*\n * @salmonui/core default theme (generated by tooling/checks/theme-css.mjs; do not edit).\n' +
    ' * Sets every --salmon-* variable on :root and on the default theme scope, in\n' +
    ' * both color schemes, with prefers-contrast overrides.\n */\n\n';
  return header + createThemeCss(undefined, { root: true, fixed: FIXED_TOKENS });
}

const css = defaultThemeCss();
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== css) {
    console.error('packages/core/styles/theme.css is stale; run `node tooling/checks/theme-css.mjs`.');
    process.exit(1);
  }
} else if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  writeFileSync(target, css);
  console.log(`wrote ${target.pathname}`);
}
