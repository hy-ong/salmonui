export type PivotLocaleTextKey = keyof typeof PIVOT_DEFAULT_LOCALE_TEXT;
export type PivotLocaleText = Partial<Record<PivotLocaleTextKey, string>>;

/** Text lookup with `{param}` substitution. */
export type PivotText = (key: PivotLocaleTextKey, params?: Readonly<Record<string, string | number>>) => string;

export function createText(overrides: PivotLocaleText | undefined): PivotText {
  return (key, params) => {
    const template: string = overrides?.[key] ?? PIVOT_DEFAULT_LOCALE_TEXT[key];
    return params ? template.replace(/\{(\w+)\}/g, (m, name: string) => (params[name] === undefined ? m : String(params[name]))) : template;
  };
}
